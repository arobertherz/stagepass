/**
 * @param {string} markdown guide body, without the managed header
 * @param {string} [cliVersion]
 */
export function renderStagepassAgentsFile(markdown, cliVersion = CLI_VERSION) {
  const md = markdown.endsWith('\n') ? markdown : `${markdown}\n`;
  const body = `${STAGEPASS_AGENTS_NOTICE}\n\n${md}`;
  const header = `<!-- stagepass:managed cli=${cliVersion} sha256=${sha256(body)} -->`;
  return `${header}\n${body}`;
}

/**
 * @param {string} raw
 * @returns {{ status: 'managed', cli: string, body: string } | { status: 'edited', cli: string } | { status: 'unmanaged' }}
 */
export function inspectStagepassAgents(raw) {
  const text = normalizeNewlines(raw);
  const match = HEADER_RE.exec(text);
  if (!match) return { status: 'unmanaged' };
  const body = text.slice(match[0].length);
  if (sha256(body) !== match[2]) return { status: 'edited', cli: match[1] };
  return { status: 'managed', cli: match[1], body };
}

/**
 * @param {object} input
 * @param {string | null} input.existing null when the file is missing
 * @param {string} input.desired
 * @param {boolean} input.assumeYes
 * @param {boolean} input.interactive
 * @returns {{ action: 'create' | 'update' | 'current' | 'ask' | 'hint', reason?: 'edited' | 'unmanaged' }}
 */
export function decideStagepassAgentsUpdate({ existing, desired, assumeYes, interactive }) {
  if (existing == null) return { action: 'create' };
  const found = inspectStagepassAgents(existing);
  if (normalizeNewlines(existing) === normalizeNewlines(desired)) return { action: 'current' };
  if (found.status === 'managed') return { action: 'update' };
  if (assumeYes) return { action: 'update', reason: found.status };
  if (interactive) return { action: 'ask', reason: found.status };
  return { action: 'hint', reason: found.status };
}

